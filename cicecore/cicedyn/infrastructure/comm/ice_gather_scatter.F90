            end do

            !*** fill outside halo for extended grid gather

            if (lext) then
               ! south
               if (jblock == 1) then
                  do j = 1, nghost
                  do i = ilo, ihi
                     LARRAY_G(this_block%i_glob(i),j-nghost) = msg_buffer(i,j)
                  enddo
                  enddo
               endif

               ! north
               if (jblock == nblocks_y) then
                  do j = 1, nghost
